import time

# 오늘은 휴일이다. 황금같은 휴일 시간을 그냥 흘려보내고 싶지는 않다. 조금이라도 더 효율적으로 쓰고, 남는 시간에는 마음 편히 쉬려고 한다.  
# 오늘 해야 할 일이 몇 가지 있다. 세탁기를 돌려야 하고, 청소도 해야 한다. 샤워도 해야 하고, 밀려있던 공부도 하려고 한다. 이 모든 일을 마친 뒤에는 꿀같은 휴식을 취할 예정이다.  
# 그렇다면 조금이라도 더 빨리 쉬기 위해서는 이 일들을 어떻게 처리해야 할까? 이 상황을 통해 동기와 비동기의 개념을 이해해보겠다.  

# 1. 동기  
# 먼저 동기 방식 (Syncronous) 부터 살펴보자.  
# 동기란, 어떤 작업을 시작하면 그 작업이 끝날 때까지 기다린 뒤 다음 작업을 진행하는 방식을 가리킨다. 즉, 하나의 일이 완료되어야만 다음 일을 시작할 수 있는 것이다.  
# 앞서 예시로 든 휴일의 할 일들을 동기 방식으로 처리한다고 생각해보면 아래와 같다.  
# (1) 먼저 세탁기를 돌린다. 그리고 세탁이 끝날 때까지 아무것도 하지 않고 기다린다.  
# (2) 세탁이 끝나면 그제서야 청소를 시작한다. 로봇청소기에게 청소를 맡겼지만, 청소가 끝날 때까지 또 기다린다.  
# (3) 청소가 끝나면 샤워를 하고, 샤워가 끝난 뒤에는 공부를 시작한다.  
# 그리고 공부까지 모두 끝마친 후에야 드디어 휴식을 취할 수 있다.   

# 이 동기 방식을 파이썬 코드로 작성해보면 다음과 같다.  

start = time.time()

def time_log(msg):
    print(f"{time.time()-start:4.1f}초 :: {msg}")

def run_washing_machine():
    time_log("세탁기 시작")
    time.sleep(4)
    time_log("세탁기 종료")
    
def run_robot_vacuum():
    time_log("로봇청소기 시작")
    time.sleep(3)
    time_log("로봇청소기 종료")

def take_shower():
    time_log("샤워 시작")
    time.sleep(2)
    time_log("샤워 종료")

def study():
    time_log("공부 시작")
    time.sleep(2)
    time_log("공부 종료")

def main():
    run_washing_machine()
    run_robot_vacuum()
    take_shower()
    study()

main()

# 이 방식은 흐름이 단순하고 이해하기 쉽다는 장점이 있다. 작업이 순서대로 진행되기 때문에, 결과를 예측하기도 쉽다.  
# 하지만 단점도 있다. 세탁기나 로봇청소기처럼 내가 직접 계속 신경 쓰지 않아도 되는 작업을, 그 작업이 끝날 때까지 가만히 기다려야만 한다는 점이다.  
# 그 시간 동안 다른 일을 할 수 있음에도 불구하고 아무것도 하지 못하고 비효율적으로 시간을 보내게 된다.  
# 즉, 동기 방식은 작업의 순서는 명확하지만, 굳이 직접 처리하지 않아도 되는 작업에 대한 대기 시간이 길어질 수 있는 방식인 것이다.  